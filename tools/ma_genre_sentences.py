"""Generate the "play <genre>" sentences from Music Assistant's genre list.

Writes custom_sentences/en/music_genres.yaml (the PlayGenre intent and the
{genre} list) and custom_templates/voice_pack_genres.jinja (genre name -> MA id).
Rerun it after MA's genres change.

Run inside the Home Assistant container, which has the MA URL and token:
    python3 ma_genre_sentences.py /config [--min-tracks 5]
or pass --url and --token (token on stdin with --token -) to run elsewhere.
"""

import argparse
import json
import logging
import re
import sys
import urllib.request
from pathlib import Path

log = logging.getLogger("ma_genre_sentences")

SENTENCES = [
    "[(could|can|would|will) you] [please] (play|put on) [me] [some] {genre} [music|songs|tracks] [please]",
    "(I want|I would like|I'd like) to (hear|listen to) [some] {genre} [music]",
    "let's (hear|listen to) [some] {genre} [music]",
]
# "play jazz in the kitchen": a named room instead of the satellite's.
ROOM_SENTENCES = [
    "[(could|can|would|will) you] [please] (play|put on) [me] [some] {genre} [music|songs|tracks] (in|on) [the] {area} [(speaker|speakers)] [please]",
    "(I want|I would like|I'd like) to (hear|listen to) [some] {genre} [music] (in|on) [the] {area} [(speaker|speakers)]",
    "let's (hear|listen to) [some] {genre} [music] (in|on) [the] {area} [(speaker|speakers)]",
]


def ha_credentials(config_dir):
    entries = json.loads((Path(config_dir) / ".storage" / "core.config_entries").read_text())["data"]["entries"]
    entry = next(e for e in entries if e["domain"] == "music_assistant")
    data = entry["data"]
    return data.get("url", "http://localhost:8095"), data.get("token") or data.get("access_token")


def ma_call(url, token, command, **args):
    req = urllib.request.Request(
        url.rstrip("/") + "/api",
        data=json.dumps({"command": command, "args": args}).encode(),
        headers={"Content-Type": "application/json", "Authorization": f"Bearer {token}"},
    )
    with urllib.request.urlopen(req, timeout=30) as r:
        return json.load(r)


def spoken(name):
    """Forms of a genre name that speech-to-text produces ("R&B" -> "r and b")."""
    s = name.lower().replace("&", " and ").replace("-", " ").replace("/", " ")
    s = re.sub(r"[^a-z0-9' ]", "", s)
    s = re.sub(r"\s+", " ", s).strip()
    forms = {s} if s else set()
    if " and " in s:
        forms.add(s.replace(" and ", " n "))
    return sorted(forms)


def build(genres, min_tracks):
    """genres: [{"id", "name", "tracks"}] -> (sentences dict, jinja text)."""
    keep = sorted((g for g in genres if g["tracks"] >= min_tracks), key=lambda g: g["name"].lower())
    values, seen = [], set()
    for g in keep:
        for form in spoken(g["name"]):
            if form in seen:
                log.debug("skip duplicate spoken form %r (%s)", form, g["name"])
                continue
            seen.add(form)
            values.append({"in": form, "out": g["name"]})
    sentences = {
        "language": "en",
        "intents": {
            "PlayGenre": {
                "data": [{"sentences": SENTENCES, "requires_context": {"area": {"slot": True}}},
                         {"sentences": ROOM_SENTENCES}]
            }
        },
        "lists": {"genre": {"values": values}},
    }
    # Keyed by lowercase name and spoken form, so the LLM's "rock" or "r and b" works too.
    ids = {}
    for g in keep:
        for key in [g["name"].lower()] + spoken(g["name"]):
            ids.setdefault(key, str(g["id"]))
    jinja = (
        "{#- Generated by tools/ma_genre_sentences.py: Music Assistant genre name -> id. -#}\n"
        "{%- macro vp_genre_id(name) -%}{{ " + json.dumps(ids, sort_keys=True) + ".get(name | lower | trim, '') }}{%- endmacro -%}\n"
    )
    return sentences, jinja


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("config_dir", help="Home Assistant /config; outputs go under it")
    ap.add_argument("--url", help="Music Assistant URL (default: from HA's config entry)")
    ap.add_argument("--token", help="MA token, or - to read it from stdin (default: from HA's config entry)")
    ap.add_argument("--min-tracks", type=int, default=5, help="skip genres with fewer tracks (default 5)")
    ap.add_argument("-v", "--verbose", action="store_true")
    a = ap.parse_args()
    logging.basicConfig(level=logging.DEBUG if a.verbose else logging.INFO, format="%(message)s")

    url, token = (a.url, a.token) if a.url and a.token else ha_credentials(a.config_dir)
    if a.token == "-":
        token = sys.stdin.readline().strip()

    raw = ma_call(url, token, "music/genres/library_items", limit=5000)
    counts = ma_call(url, token, "music/genres/media_counts", genre_ids=[str(g["item_id"]) for g in raw])
    genres = [{"id": g["item_id"], "name": g["name"], "tracks": counts.get(str(g["item_id"]), {}).get("track", 0)} for g in raw]
    log.debug("%d genres from MA", len(genres))

    sentences, jinja = build(genres, a.min_tracks)
    out = Path(a.config_dir)
    # JSON is valid YAML, and keeps the hassil template characters quoted.
    (out / "custom_sentences" / "en" / "music_genres.yaml").write_text(
        "# Generated by ha-voice-pack tools/ma_genre_sentences.py; handled by packages/voice_music.yaml.\n"
        + json.dumps(sentences, indent=2) + "\n"
    )
    (out / "custom_templates" / "voice_pack_genres.jinja").write_text(jinja)
    log.info("%d of %d genres (>= %d tracks), %d spoken forms",
             len(set(v["out"] for v in sentences["lists"]["genre"]["values"])), len(genres), a.min_tracks,
             len(sentences["lists"]["genre"]["values"]))


if __name__ == "__main__":
    main()
